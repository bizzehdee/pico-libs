#include "rtc_i2c.h"

uint8_t RTCI2C::readRegister(uint8_t reg)
{
   uint8_t value = 0;
   i2c_dev->write_then_read(&reg, 1, &value, 1);
   return value;
}

void RTCI2C::writeRegister(uint8_t reg, uint8_t val)
{
   uint8_t buffer[2] = {reg, val};
   i2c_dev->write(buffer, 2);
}
